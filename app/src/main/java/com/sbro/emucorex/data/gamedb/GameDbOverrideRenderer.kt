package com.sbro.emucorex.data.gamedb

import android.content.Context
import android.util.Log
import com.sbro.emucorex.BuildConfig
import java.io.File

/**
 * Turns the edits stored in [GameDbUserOverrides] into the YAML overlay the emulator core loads
 * after `GameIndex.yaml` and the bundled `emucorex_overrides.yaml`.
 *
 * The core replaces a whole section when an override names it, so every emitted section restates
 * the values that must survive. Round and clamp modes merge per key instead, so only the edited
 * keys are emitted; `-1` there means "do not override, keep the user's own mode".
 */
object GameDbOverrideRenderer {
    const val OVERLAY_FILE_NAME = "emucorex_user_overrides.yaml"

    private const val TAG = "GameDbOverrideRenderer"
    private const val RESOURCE_ROOT = "resources"
    private const val DISABLED_MODE = "-1"
    private const val DEFAULT_ADDED_VALUE = "1"

    private val HEADER = """
        # Generated by EmuCoreX from the in-app GameDB browser.
        # Do not edit by hand: the app rewrites this file whenever a GameDB fix is changed.
        # Applied after GameIndex.yaml and emucorex_overrides.yaml, so it always wins.
    """.trimIndent()

    /**
     * Rewrites [OVERLAY_FILE_NAME] when it can be stale.
     *
     * @param force regenerate even when the app stamp is unchanged (used right after an edit).
     * @return the overlay file when it exists and has content, null when no override is stored.
     */
    fun render(context: Context, dataRoot: File, force: Boolean = false): File? {
        val appContext = context.applicationContext
        val overrides = GameDbUserOverrides(appContext)
        val games = overrides.games.value
        val target = File(File(dataRoot, RESOURCE_ROOT), OVERLAY_FILE_NAME)
        val stamp = appStamp(appContext)

        if (!force && overrides.renderStamp() == stamp) {
            if (games.isEmpty()) {
                if (target.isFile) target.delete()
                return null
            }
            if (target.isFile) return target
        }

        if (games.isEmpty()) {
            if (target.isFile) target.delete()
            overrides.markRendered(stamp)
            return null
        }

        return runCatching {
            val baseline = GameDbCatalogRepository(appContext).loadEntries().associateBy { it.serial.uppercase() }
            val yaml = buildOverlay(games, baseline)
            val written = if (yaml.isBlank()) {
                target.delete()
                null
            } else {
                target.parentFile?.mkdirs()
                // Write-then-rename: a cancelled or killed process must never leave the core with a
                // half-written overlay that fails to parse.
                val temp = File(target.parentFile, "${target.name}.tmp")
                temp.writeText(yaml)
                if (!temp.renameTo(target)) {
                    target.writeText(yaml)
                    temp.delete()
                }
                target
            }
            overrides.markRendered(stamp)
            written
        }.onFailure { error ->
            Log.e(TAG, "Unable to write the GameDB user overlay", error)
        }.getOrNull()
    }

    /** Visible for tests: renders the overlay text without touching the file system. */
    internal fun buildOverlay(
        games: Map<String, GameDbGameOverride>,
        baseline: Map<String, GameDbCatalogEntry>
    ): String {
        val builder = StringBuilder(HEADER).append('\n')
        games.toSortedMap().forEach { (serial, game) ->
            val body = buildGame(game, baseline[serial.uppercase()])
            if (body.isNotBlank()) {
                builder.append(serial.uppercase()).append(":\n").append(body)
            }
        }
        return if (builder.length <= HEADER.length + 1) "" else builder.toString()
    }

    private fun buildGame(game: GameDbGameOverride, baseline: GameDbCatalogEntry?): String {
        val settings = baseline?.settings.orEmpty()
        val builder = StringBuilder()

        buildListSection(GameDbFixSection.GAME_FIXES, game, settings)?.let(builder::append)
        buildMapSection(GameDbFixSection.GS_HW_FIXES, game, settings)?.let(builder::append)
        buildMapSection(GameDbFixSection.SPEED_HACKS, game, settings)?.let(builder::append)
        buildModeSection(GameDbFixSection.ROUND_MODES, game)?.let(builder::append)
        buildModeSection(GameDbFixSection.CLAMP_MODES, game)?.let(builder::append)

        return builder.toString()
    }

    private fun buildListSection(
        section: GameDbFixSection,
        game: GameDbGameOverride,
        settings: List<GameDbSettingItem>
    ): String? {
        val baselineIds = settings.filter { it.category.section == section }.map { it.id }
        val addedIds = game.addedKeys()
            .filter { GameDbFixId.sectionOf(it) == section && it !in baselineIds }
            .sorted()
        val enabledIds = (baselineIds + addedIds).filter { game.isEnabled(it) }
        if (enabledIds == baselineIds) return null

        val builder = StringBuilder("  ").append(section.yamlName).append(':')
        if (enabledIds.isEmpty()) {
            builder.append(" []\n")
        } else {
            builder.append('\n')
            enabledIds.forEach { id ->
                builder.append("    - ").append(GameDbFixId.keyOf(id)).append('\n')
            }
        }
        return builder.toString()
    }

    private fun buildMapSection(
        section: GameDbFixSection,
        game: GameDbGameOverride,
        settings: List<GameDbSettingItem>
    ): String? {
        val baselineValues = LinkedHashMap<String, String>()
        settings.filter { it.category.section == section }.forEach { baselineValues[it.id] = it.value }

        val allIds = LinkedHashSet(baselineValues.keys)
        game.addedKeys().filter { GameDbFixId.sectionOf(it) == section }.sorted().forEach(allIds::add)

        val effective = LinkedHashMap<String, String>()
        allIds.forEach { id ->
            if (!game.isEnabled(id)) return@forEach
            effective[id] = game.valueOf(id) ?: baselineValues[id] ?: DEFAULT_ADDED_VALUE
        }

        val changed = effective.size != baselineValues.size ||
            effective.any { (id, value) -> baselineValues[id] != value }
        if (!changed) return null

        val builder = StringBuilder("  ").append(section.yamlName).append(':')
        if (effective.isEmpty()) {
            builder.append(" {}\n")
        } else {
            builder.append('\n')
            effective.forEach { (id, value) ->
                builder.append("    ").append(GameDbFixId.keyOf(id)).append(": ").append(value).append('\n')
            }
        }
        return builder.toString()
    }

    private fun buildModeSection(section: GameDbFixSection, game: GameDbGameOverride): String? {
        val edits = game.edited(section).toSortedMap()
        if (edits.isEmpty()) return null

        val builder = StringBuilder("  ").append(section.yamlName).append(":\n")
        edits.forEach { (id, override) ->
            val value = when {
                !override.enabled -> DISABLED_MODE
                override.value != null -> override.value
                // A line added from the browser has no bundled value to fall back to. Without this
                // default the section would be emitted empty instead of applying the line.
                override.added -> DEFAULT_ADDED_VALUE
                else -> return@forEach
            }
            builder.append("    ").append(GameDbFixId.keyOf(id)).append(": ").append(value).append('\n')
        }
        return builder.toString()
    }

    private fun appStamp(context: Context): String = runCatching {
        val info = context.packageManager.getPackageInfo(context.packageName, 0)
        "${info.lastUpdateTime}:${BuildConfig.VERSION_CODE}"
    }.getOrDefault(BuildConfig.VERSION_CODE.toString())
}
